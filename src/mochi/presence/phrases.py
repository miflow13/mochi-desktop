class PhraseBank:
    """Choose phrases while avoiding a short in-memory repetition window."""

    def __init__(
        self,
        *,
        rng: random.Random | None = None,
        recent_limit: int = 12,
    ) -> None:
        self._rng = rng or random.Random()
        self._recent: deque[str] = deque(maxlen=max(1, recent_limit))

    def choose(
        self,
        category: str,
        *,
        exclude_recent: bool = True,
        remember: bool = False,
    ) -> str:
        try:
            choices = PHRASES[category]
        except KeyError as exc:
            raise KeyError(f"unknown Mochi phrase category: {category}") from exc
        return self.choose_from(
            choices,
            exclude_recent=exclude_recent,
            remember=remember,
        )

    def choose_context(
        self,
        context: str,
        *,
        exclude_recent: bool = True,
        remember: bool = False,
    ) -> str:
        try:
            choices = CONTEXT_PHRASES[context]
        except KeyError as exc:
            raise KeyError(f"unknown Mochi phrase context: {context}") from exc
        return self.choose_from(
            choices,
            exclude_recent=exclude_recent,
            remember=remember,
        )

    def choose_from(
        self,
        choices: Iterable[str],
        *,
        exclude_recent: bool = True,
        remember: bool = False,
    ) -> str:
        pool = tuple(choices)
        if not pool:
            raise ValueError("phrase choices must not be empty")
        if exclude_recent:
            fresh = tuple(item for item in pool if item not in self._recent)
            if fresh:
                pool = fresh
        selected = self._rng.choice(pool)
        if remember:
            self.remember(selected)
        return selected

    def remember(self, text: str) -> None:
        self._recent.append(text)

    @property
    def recent(self) -> tuple[str, ...]:
        return tuple(self._recent)
